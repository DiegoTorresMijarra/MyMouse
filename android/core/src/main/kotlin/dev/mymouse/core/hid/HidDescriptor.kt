package dev.mymouse.core.hid

/**
 * Descriptor HID compuesto: ratón (id 1), teclado (id 2) y consumo (id 3). Hay dos versiones del ratón (docs/spec-v5-bluetooth-completo.md §4):
 * - **Con scroll fino:** la rueda y la rueda horizontal (AC Pan) van cada una en una colección lógica con su *Resolution Multiplier*
 *   (informe *feature* del id 1, de un byte; ver [ScrollResolution]). Es el patrón de los ratones de "scroll suave" de Windows.
 * - **Antiguo:** sin multiplicador, como hasta la v4. Por si algún PC se porta mal con el nuevo.
 * El informe de entrada del ratón es el mismo en las dos (botones, X, Y, rueda, pan: 5 bytes).
 */
object HidDescriptor {
    private const val MOUSE_ID = HidMapper.MOUSE_ID
    private const val KEYBOARD_ID = HidMapper.KEYBOARD_ID
    private const val CONSUMER_ID = HidMapper.CONSUMER_ID

    /** Cabecera del ratón hasta X e Y (común a las dos versiones, sin la rueda). */
    private val MOUSE_START = intArrayOf(
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, MOUSE_ID,
        0x09, 0x01, 0xA1, 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x05, 0x15, 0x00, 0x25, 0x01, 0x95, 0x05, 0x75, 0x01, 0x81, 0x02,
        0x95, 0x01, 0x75, 0x03, 0x81, 0x01,
    )

    /** Ratón sin multiplicador: X, Y y rueda en un mismo elemento; AC Pan aparte. */
    private val MOUSE_LEGACY = MOUSE_START + intArrayOf(
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06,
        0x05, 0x0C, 0x0A, 0x38, 0x02, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06,
        0xC0, 0xC0,
    )

    /** Ratón con multiplicador: X e Y; después la rueda y AC Pan, cada una con su multiplicador (feature de 2 bits) y 4 bits de relleno. */
    private val MOUSE_FINE = MOUSE_START + intArrayOf(
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06,
        // Rueda: colección lógica con Resolution Multiplier (0x48) lógico 0–1, físico 1–120, y la rueda (0x38).
        0xA1, 0x02,
        0x09, 0x48, 0x15, 0x00, 0x25, 0x01, 0x35, 0x01, 0x45, 0x78, 0x75, 0x02, 0x95, 0x01, 0xB1, 0x02,
        0x09, 0x38, 0x15, 0x81, 0x25, 0x7F, 0x35, 0x00, 0x45, 0x00, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06,
        0xC0,
        // Rueda horizontal: lo mismo, con AC Pan (página de consumo, 0x0238).
        0xA1, 0x02,
        0x09, 0x48, 0x15, 0x00, 0x25, 0x01, 0x35, 0x01, 0x45, 0x78, 0x75, 0x02, 0x95, 0x01, 0xB1, 0x02,
        0x05, 0x0C, 0x0A, 0x38, 0x02, 0x15, 0x81, 0x25, 0x7F, 0x35, 0x00, 0x45, 0x00, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06,
        0xC0,
        // Relleno del informe feature hasta el byte (4 bits, constante).
        0x75, 0x04, 0x95, 0x01, 0xB1, 0x03,
        0xC0, 0xC0,
    )

    private val KEYBOARD_AND_CONSUMER = intArrayOf(
        // Teclado (id 2)
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, KEYBOARD_ID,
        0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
        0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
        0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65, 0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00,
        0xC0,
        // Consumo (id 3)
        0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01, 0x85, CONSUMER_ID,
        0x15, 0x00, 0x26, 0xFF, 0x03, 0x19, 0x00, 0x2A, 0xFF, 0x03, 0x75, 0x10, 0x95, 0x01, 0x81, 0x00,
        0xC0,
    )

    /** El descriptor que se registra: con [fineScroll] el del ratón con *Resolution Multiplier*, y si no el de la v4. */
    fun build(fineScroll: Boolean): ByteArray =
        ((if (fineScroll) MOUSE_FINE else MOUSE_LEGACY) + KEYBOARD_AND_CONSUMER).map { it.toByte() }.toByteArray()
}
